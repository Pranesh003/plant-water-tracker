// Lookup Helper Function matching any query to the plant database
export function findPlantMatch(species = "", name = "") {
  const q = `${name} ${species}`.toLowerCase().trim();
  if (!q) return plantDatabase[0];

  // Direct match by keywords
  for (const plant of plantDatabase) {
    if (plant.keywords.some((kw) => q.includes(kw))) {
      return plant;
    }
  }

  // Fallback default
  return {
    name: name || "House Plant",
    species: species || "Indoor Variety",
    temp: "20-26°C",
    humidity: "45-65%",
    sunlight: "Bright Indirect",
    frequency: 7,
    waterMl: 350,
    category: "Indoor Foliage"
  };
}
